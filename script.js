document.getElementById("jina").addEventListener("input", function() {
  const thamani = this.value.trim();
  if (thamani.length >= 2) {
    this.classList.add("field-sawa");
    this.classList.remove("field-kosa");
    document.getElementById("jina-error").textContent = "";
  }
});

document.getElementById("simu").addEventListener("input", function() {
  const thamani = this.value.trim();
  if (simuNiSahihi(thamani)) {
    this.classList.add("field-sawa");
    this.classList.remove("field-kosa");
    document.getElementById("simu-error").textContent = "";
  }
});

document.getElementById("email").addEventListener("input", function() {
  const thamani = this.value.trim();
  if (thamani === "" || emailNiSahihi(thamani)) {
    this.classList.remove("field-kosa");
    document.getElementById("email-error").textContent = "";
    if (thamani !== "") this.classList.add("field-sawa");
  }
});


